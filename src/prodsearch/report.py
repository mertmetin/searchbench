"""results/results.json -> results/summary.md and results/exact_at_10.png."""

from __future__ import annotations

import json

from .evaluate import RESULTS_DIR

ORDER = ["title_bm25_2014", "fields_bm25", "dense", "hybrid", "hybrid_rerank"]
LABELS = {
    "title_bm25_2014": "2014: keyword search on titles",
    "fields_bm25": "Keyword search on all fields (BM25)",
    "dense": "Semantic search (embeddings)",
    "hybrid": "Hybrid (BM25 + semantic, RRF)",
    "hybrid_rerank": "Hybrid + cross-encoder rerank",
}
SURFACE, INK, INK_2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
OLD, NEW = "#2a78d6", "#eb6834"


def build() -> None:
    results = json.loads((RESULTS_DIR / "results.json").read_text())
    keys = [k for k in ORDER if k in results]
    base = results["title_bm25_2014"]

    rows = [
        "| Approach | NDCG@10 | Exact matches in top 10 | MRR (first exact match) | Unlabelled in top 10 | Latency |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for k in keys:
        m = results[k]
        rows.append(
            f"| {LABELS[k]} | **{m['ndcg@10']:.3f}** | {m['precision_exact@10']:.1%} | {m['mrr_exact']:.3f} | "
            f"{m['unlabelled@10']:.0%} | {m['ms_per_query']:.1f} ms |"
        )
    best = max(keys, key=lambda k: results[k]["ndcg@10"])
    old_q, new_q = base["per_query_ndcg"], results[best]["per_query_ndcg"]
    wins = sum(new_q[q] > old_q[q] + 1e-9 for q in new_q)
    losses = sum(new_q[q] < old_q[q] - 1e-9 for q in new_q)
    md = [
        "# Results\n",
        "480 WANDS queries, graded labels (Exact = 1, Partial = 0.5). Generated by `prodsearch report`.\n",
        "\n".join(rows) + "\n",
        f"Per query, **{LABELS[best]}** beats the 2014 approach on {wins} queries and loses on {losses} "
        f"(ties: {len(new_q) - wins - losses}).\n",
    ]
    (RESULTS_DIR / "summary.md").write_text("\n".join(md))
    _figure(results, keys)
    print("Wrote results/summary.md and results/exact_at_10.png")


def _figure(results: dict, keys: list[str]) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    vals = [results[k]["precision_exact@10"] for k in keys]
    fig, ax = plt.subplots(figsize=(8, 0.5 * len(keys) + 1.3), dpi=200)
    fig.patch.set_facecolor(SURFACE)
    ax.set_facecolor(SURFACE)
    ys = list(range(len(keys)))[::-1]
    for y, k, v in zip(ys, keys, vals, strict=True):
        ax.barh(y, v, height=0.62, color=OLD if k == "title_bm25_2014" else NEW, edgecolor=SURFACE, linewidth=2)
        ax.text(v + 0.008, y, f"{v:.0%}", va="center", fontsize=9, color=INK)
    ax.set_yticks(ys, [LABELS[k] for k in keys], fontsize=9, color=INK)
    ax.set_xlim(0, max(vals) * 1.2)
    ax.xaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1.0, decimals=0))
    ax.tick_params(axis="x", colors=INK_2, labelsize=8, length=0)
    ax.tick_params(axis="y", length=0)
    ax.grid(axis="x", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for s in ax.spines.values():
        s.set_visible(False)
    ax.set_title(
        "Share of the first 10 results that people judged an exact match", loc="left", fontsize=10.5, color=INK, pad=12
    )
    fig.tight_layout()
    fig.savefig(RESULTS_DIR / "exact_at_10.png", facecolor=SURFACE)
    plt.close(fig)
